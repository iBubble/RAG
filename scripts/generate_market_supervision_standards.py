# 2. 市场监督管理行政处罚程序规定（总局令第42号）
DOC_42 = """# 市场监督管理行政处罚程序规定
（2021年修正版，国家市场监督管理总局令第42号）

## 第一章 总 则 与 管 辖
- 市场监管行政处罚必须坚持公正、公开，程序合法，以事实为依据，与违法行为事实、性质、情节及社会危害程度相当。
- 行政处罚由违法行为发生地的县级以上市场监管部门管辖。网络交易行为由经营者实际经营地管辖。

## 第二章 立 案 与 调 查
- **第十八条 立案期限**：市场监管部门对依据监督检查职权、投诉举报、移交线索发现的涉嫌违法行为，应当自发现或收到材料之日起七个工作日内予以核查，决定是否立案。
- **调查取证规范**：办案人员不得少于两人，应当出示行政执法证件。依法收集书证、物证、视听资料、电子数据、证人证言、当事人陈述、勘验笔录和现场笔录。
- **第二十七条 抽样取证**：对可能灭失或以后难以取得的证据，经负责人批准可以抽样取证或先行登记保存，并在七个工作日内作出处理决定。

## 第三章 审理、告知与处罚决定
- 拟作出行政处罚前，必须向当事人送达《行政处罚告知书》，告知拟作出的处罚内容、事实、理由及依据，并告知当事人在五个工作日内享有陈述、申辩权。符合听证条件的，告知听证权利。
- **第六十四条 办案时限**：适用普通程序办理的案件，应当自立案之日起九十日内作出行政处罚决定。法律法规另有规定的除外。
"""

# 3. 规范市场监督管理行政处罚裁量权的指导意见
DOC_DISCRETION = """# 规范市场监督管理行政处罚裁量权的指导意见
（国市监法发〔2019〕244号）

## 不予行政处罚的情形
1. 违法行为轻微并及时纠正，没有造成危害后果的，不予行政处罚。
2. 初次违法且危害后果轻微并及时改正的，可以不予行政处罚（“首违不罚”）。
3. 当事人有充分证据证明不存在主观故意或者重大过失的，不予行政处罚。法律、行政法规另有规定的，从其规定。

## 从轻或者减轻行政处罚的情形
1. 积极配合市场监管部门调查，如实陈述违法事实并主动提供证据材料的；
2. 违法行为轻微，社会危害性较小的；
3. 在共同违法行为中起次要或者辅助作用的；
4. 当事人主动消除或者减轻违法行为危害后果的；
5. 其他依法应当从轻或者减轻行政处罚的情形。

## 从重行政处罚的情形
1. 涉及食品药品安全等关系人民群众生命健康，造成严重社会后果的；
2. 伪造、销毁、隐匿证据，或者抗拒、阻碍执法人员执法的；
3. 经市场监管部门责令停止违法行为后，继续实施违法行为的；
4. 屡查屡犯、在一年内因同一性质违法行为受过行政处罚的。
"""

